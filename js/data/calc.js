  const { ri, pick, fromDecimal, num } = global.U;
  const R = global.RIKA;

  /* 計算の誤差（0.1 + 0.2 など）をなくしてから有理数にする */
  const mk = (q, x, unit, exp) => {
    const s = num(x);
    return { type: 'num', q, val: fromDecimal(s), ans: s + unit, unit, exp };
  };
  const gen = (name, variants) => {
    const f = (filter) => {
      const vs = variants.filter(([lv]) => !filter || filter(lv));
      if (!vs.length) return null;
      const [lv, fn] = pick(vs);
      return Object.assign(fn(), { lv });
    };
    Object.defineProperty(f, 'name', { value: name });
    f.size = variants.length;
    return f;
  };
  /* 条件に合うまで数をえらび直す */
  const until = (fn) => { for (let i = 0; i < 500; i++) { const r = fn(); if (r) return r; } throw new Error('no case'); };

